def fault_name(code: str) -> str:
    """返回错误码的中文名。

    **未知代码原样返回代码本身**，不编造名字、也不返回空串 ——
    返回空串会让界面出现一个没有标题的告警，比看到英文码更糟。
    """
    return FAULT_NAMES.get(code, code)


def is_known(code: str) -> bool:
    """该错误码是否有正式中文名。"""
    return code in FAULT_NAMES


def unknown_codes(codes: object) -> tuple[str, ...]:
    """从一组错误码中挑出没有中文名的。

    供测试与自检使用：领域层新增了错误码而本表没跟上时，这个函数能把它们找出来。
    """
    return tuple(sorted({str(c) for c in codes if str(c) not in FAULT_NAMES}))  # type: ignore[union-attr]


